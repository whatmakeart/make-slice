"""Generate complete, empty DXF skeletons; browser exports need no Python."""
import io
import json
from pathlib import Path
import ezdxf

root = Path(__file__).resolve().parents[1]
width, height, view_height = 987654321.25, 123456789.125, 999999999.555
templates = {}
for version in ("R2000", "R12"):
    doc = ezdxf.new(version)
    doc.header["$MEASUREMENT"] = 1
    doc.header["$LUNITS"] = 2
    doc.header["$LUPREC"] = 4
    doc.header["$FILLMODE"] = 0
    doc.header["$EXTMIN"] = (0, 0, 0)
    doc.header["$EXTMAX"] = (width, height, 0)
    doc.header["$LIMMAX"] = (width, height)
    doc.header["$TDCREATE"] = 2451545.0
    doc.header["$TDUPDATE"] = 2451545.0
    if version == "R2000":
        doc.units = 4
        doc.modelspace().dxf.extmin = (0, 0, 0)
        doc.modelspace().dxf.extmax = (width, height, 0)
        doc.modelspace().dxf.limmax = (width, height)
    doc.set_modelspace_vport(view_height, (width / 2, height / 2))
    for name, color in (("CUT_OUTLINE", 1), ("ETCH_LABELS", 5), ("CUT_INTERIOR", 3), ("REFERENCE_GUIDES", 8)):
        layer=doc.layers.new(name, dxfattribs={"color": color, **({"lineweight": 18 if name in ("ETCH_LABELS","REFERENCE_GUIDES") else 0} if version == "R2000" else {})})
        if name=="REFERENCE_GUIDES": layer.off()
    stream = io.StringIO()
    doc.write(stream)
    lines = stream.getvalue().splitlines()
    pairs = [(int(lines[i]), lines[i+1]) for i in range(0, len(lines), 2)]
    for i, (code, value) in enumerate(pairs):
        if code == 9 and value == "$HANDSEED":
            pairs[i+1] = (5, "__HANDSEED__")
    start = next(i+2 for i in range(len(pairs)-1) if pairs[i] == (0, "SECTION") and pairs[i+1] == (2, "ENTITIES"))
    assert pairs[start] == (0, "ENDSEC")
    def serialize(tags):
        text = "".join(f"{code:3d}\n{value}\n" for code, value in tags)
        for number, name in ((width, "__WIDTH__"), (height, "__HEIGHT__"), (view_height, "__VIEW_HEIGHT__"), (width/2, "__CENTER_X__"), (height/2, "__CENTER_Y__")):
            text = text.replace(str(number), name)
        return text
    templates[version] = {"prefix": serialize(pairs[:start]), "suffix": serialize(pairs[start:]), "modelHandle": doc.modelspace().block_record_handle}
    assert max(int(h, 16) for h in doc.entitydb if h) < 4096
text = f"// Complete DXF skeletons generated by ezdxf {ezdxf.__version__}.\n// Regenerate with scripts/generate-dxf-template.py. Runtime needs no CAD library.\n"
text += "export const DXF_TEMPLATES = " + json.dumps(templates, ensure_ascii=True) + " as const;\n"
(root / "lib/slicer/dxf-template.ts").write_text(text)
print("Generated complete R2000 and R12 DXF templates.")
